import assert from "node:assert/strict";
import fs from "node:fs/promises";
import path from "node:path";
const repo = path.resolve(import.meta.dirname, "../../..");
const read = (file) => fs.readFile(path.join(repo, file), "utf8");
const quote = (value) => '"' + value.replaceAll('"', '""') + '"';
export const a = "00000000-0000-4000-8000-000000000001";
export const b = "00000000-0000-4000-8000-000000000002";
export const admin = "00000000-0000-4000-8000-000000000003";
export async function seedDatabase(db) {
    await db.exec(`
      create role anon; create role authenticated; create role service_role bypassrls;
      create schema auth;
      create table auth.users (id uuid primary key, email text, raw_user_meta_data jsonb);
      create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
      grant usage on schema auth, public to anon, authenticated, service_role;
    `);
    const schema = JSON.parse(await read("web/tests/fixtures/live-schema.json"));
    for (const table of schema.tables) {
      // The catalog snapshot's column text omits identity sequence metadata.
      const columns = table.name === "financial_audit_log" ? table.columns.replace("id bigint NOT NULL", "id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL") : table.columns;
      await db.exec(`create table public.${quote(table.name)} (${columns}); alter table public.${quote(table.name)} enable row level security;`);
    }
    for (const constraint of [...schema.constraints].sort((x, y) => Number(x.definition.startsWith("FOREIGN KEY")) - Number(y.definition.startsWith("FOREIGN KEY")))) {
      await db.exec(`alter table public.${quote(constraint.table)} add constraint ${quote(constraint.name)} ${constraint.definition};`);
    }
    // Like pg_dump restores, install mutually-dependent functions before
    // validating their bodies through the behavioral tests below.
    await db.exec("set check_function_bodies = off;");
    await db.exec(await read("web/tests/fixtures/live-functions.sql"));
    await db.exec("set check_function_bodies = on;");
    const baseline = await read("supabase/migrations/20260822163852_live_baseline.sql");
    const triggerFn = baseline.match(/CREATE OR REPLACE FUNCTION public\.handle_new_user\(\)[\s\S]*?\$function\$\s*$/m);
    // Match through the closing dollar quote, excluding the opening quote.
    const fnStart = baseline.indexOf("CREATE OR REPLACE FUNCTION public.handle_new_user()");
    const fnBody = baseline.indexOf("AS $function$", fnStart);
    const fnEnd = baseline.indexOf("$function$", fnBody + "AS $function$".length);
    assert.ok(triggerFn && fnStart >= 0 && fnEnd > fnStart);
    await db.exec(baseline.slice(fnStart, fnEnd + "$function$".length) + ";");
    for (const policy of schema.policies) {
      await db.exec(`create policy ${quote(policy.policyname)} on public.${quote(policy.tablename)} for ${policy.cmd} to ${policy.roles.map(quote).join(", ")} ${policy.qual ? `using (${policy.qual})` : ""} ${policy.with_check ? `with check (${policy.with_check})` : ""};`);
    }
    await db.exec("grant all on all tables in schema public to anon, authenticated, service_role;");
    await db.exec(await read("supabase/migrations/20260830010000_fix_profiles_privilege_grants.sql"));
    await db.exec(await read("supabase/migrations/20260910000000_member_status_control.sql"));
    for (const id of [a, b, admin]) {
      await db.query("insert into auth.users(id) values ($1)", [id]);
      await db.query("insert into profiles(id,username,full_name,address,city,mobile_number,account_number,payment_method) values ($1::uuid,$1::text,'Fixture','Fixture','Fixture','03000000000','fixture','EASYPAISA')", [id]);
    }
    await db.query("update profiles set role='admin' where id=$1", [admin]);

  await db.exec("create schema storage; create table storage.objects(bucket_id text, name text, primary key(bucket_id,name));");
}
